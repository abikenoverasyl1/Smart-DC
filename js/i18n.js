export const LANGS = [['kk', 'Қазақша'], ['ru', 'Русский'], ['en', 'English']];
const LOCALE = { kk: 'kk-KZ', ru: 'ru-RU', en: 'en-GB' };

let lang = 'kk';
try { const s = localStorage.getItem('sdc_lang'); if (DICT[s]) lang = s; } catch (e) { /* */ }

export const getLang = () => lang;
export const locale = () => LOCALE[lang];

export function t(key, p = {}) {
  const s = DICT[lang][key] ?? DICT.kk[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => {
    const v = p[k];
    if (typeof v === 'string' && v.startsWith('@')) return t(v.slice(1));
    return v ?? '';
  });
}

// HTML-дегі data-i18n атрибуттары бар элементтерді аудару
export function applyStatic() {
  document.documentElement.lang = lang;
  document.title = t('meta.title');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-aria]').forEach(el => el.setAttribute('aria-label', t(el.dataset.i18nAria)));
}

export function setLang(l) {
  if (!DICT[l]) return;
  lang = l;
  try { localStorage.setItem('sdc_lang', l); } catch (e) { /* */ }
  applyStatic();
}
